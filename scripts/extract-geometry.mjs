#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import {
  computeBounds,
  OPTIONAL_ROUTES,
  REQUIRED_ROUTES,
  ROUTE_WHITELIST,
  serializeGeometryData,
  snapCameras,
  transformOverpassResponse,
} from "./geometry-transform.mjs";

const SNAPSHOT_DATE = "2026-07-20T00:00:00Z";
const BOUNDS = { minLat: 32.55, minLon: -97.55, maxLat: 33.05, maxLon: -96.55 };
const ENDPOINTS = [
  "https://overpass-api.de/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter",
];
const QUERY = `[out:json][timeout:180][date:"${SNAPSHOT_DATE}"];
way["highway"~"^(motorway|trunk)$"](${BOUNDS.minLat},${BOUNDS.minLon},${BOUNDS.maxLat},${BOUNDS.maxLon})->.roads;
rel(bw.roads)["type"="route"]["route"="road"]->.roadrels;
way["natural"="water"](${BOUNDS.minLat},${BOUNDS.minLon},${BOUNDS.maxLat},${BOUNDS.maxLon})->.waterways;
(
  rel["natural"="water"](${BOUNDS.minLat},${BOUNDS.minLon},${BOUNDS.maxLat},${BOUNDS.maxLon});
  rel["water"="river"](${BOUNDS.minLat},${BOUNDS.minLon},${BOUNDS.maxLat},${BOUNDS.maxLon});
)->.waterrels;
.roads out body geom;
.roadrels out body;
.waterways out body geom;
.waterrels out body geom;`;
const MAX_RAW_BYTES = 70 * 1024;
const CAMERA_TARGETS = [
  { id: "CAM-021", route: "I-35E", lonlat: [-96.91, 32.68] },
  { id: "CAM-052", route: "I-35E", lonlat: [-96.83, 32.81] },
  { id: "CAM-063", route: "I-35E", lonlat: [-96.828, 32.86] },
  { id: "CAM-114", route: "US-75", lonlat: [-96.769, 32.924] },
  { id: "CAM-131", route: "I-635", lonlat: [-96.87, 32.93] },
  { id: "CAM-142", route: "I-635", lonlat: [-96.71, 32.91] },
  { id: "CAM-155", route: "I-635", lonlat: [-96.63, 32.82] },
  { id: "CAM-207", route: "I-30", lonlat: [-96.76, 32.772] },
  { id: "CAM-218", route: "I-30", lonlat: [-96.86, 32.77] },
  { id: "CAM-233", route: "I-30", lonlat: [-97.32, 32.75] },
  { id: "CAM-301", route: "I-35W", lonlat: [-97.32, 32.8] },
  { id: "CAM-317", route: "I-820", lonlat: [-97.4, 32.84] },
];

async function downloadSnapshot() {
  const failures = [];
  for (const endpoint of ENDPOINTS) {
    try {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: {
          accept: "application/json",
          "content-type": "application/x-www-form-urlencoded;charset=UTF-8",
          "user-agent": "Coasta DFW geometry extractor/1.0 (+https://coasta.app)",
        },
        body: `data=${encodeURIComponent(QUERY)}`,
        signal: AbortSignal.timeout(240_000),
      });
      if (!response.ok) {
        const body = (await response.text()).replace(/\s+/g, " ").slice(0, 500);
        failures.push(new Error(`${endpoint} returned ${response.status}: ${body}`));
        continue;
      }
      const raw = await response.text();
      const parsed = JSON.parse(raw);
      if (!Array.isArray(parsed.elements)) {
        failures.push(new Error(`${endpoint} did not return Overpass elements`));
        continue;
      }
      return { endpoint, raw, parsed };
    } catch (error) {
      failures.push(error instanceof Error ? error : new Error(String(error)));
    }
  }
  throw new AggregateError(failures, "No Overpass endpoint served the fixed snapshot");
}

function moduleHeader(endpoint, responseHash) {
  return `/*\nGenerated by scripts/extract-geometry.mjs. Do not edit.\nEndpoint: ${endpoint}\nSnapshot: ${SNAPSHOT_DATE}\nRaw response sha256: ${responseHash}\nExact Overpass query:\n${QUERY}\n*/\n`;
}

function configurations() {
  const attempts = [45, 70, 95, 115].map((roadToleranceMeters) => ({
    roadToleranceMeters, coordinateDigits: 6, allowedRoutes: ROUTE_WHITELIST,
  }));
  attempts.push({ roadToleranceMeters: 115, coordinateDigits: 5, allowedRoutes: ROUTE_WHITELIST });
  for (let kept = OPTIONAL_ROUTES.length - 1; kept >= 0; kept -= 1) {
    attempts.push({
      roadToleranceMeters: 115,
      coordinateDigits: 5,
      allowedRoutes: [...REQUIRED_ROUTES, ...OPTIONAL_ROUTES.slice(0, kept)],
    });
  }
  return attempts;
}


function assertCandidate(candidate) {
  const routes = new Set(candidate.result.stats.routes);
  for (const route of REQUIRED_ROUTES) {
    if (!routes.has(route)) throw new RangeError(`Missing required route ${route}`);
    const span = candidate.result.corridorSpans[route];
    if (!span || span.retainedPercent < 80) {
      throw new RangeError(`${route} retained less than 80 percent of its raw span`);
    }
  }
  if (candidate.result.roadSegments.some((segment) => segment.points.length < 2)) {
    throw new RangeError("A road segment has fewer than two points");
  }
  if (candidate.result.water.rings.some((ring) =>
    ring.length < 4 || JSON.stringify(ring[0]) !== JSON.stringify(ring.at(-1)))) {
    throw new RangeError("A water ring is open or too short");
  }
  if (candidate.cameras.length !== 12 ||
    new Set(candidate.cameras.map((camera) => camera.id)).size !== 12) {
    throw new RangeError("Camera identity invariant failed");
  }
  if (candidate.rawBytes > MAX_RAW_BYTES) {
    throw new RangeError(`Generated module is ${candidate.rawBytes} bytes`);
  }
}

function selectCandidate(parsed, header) {
  const attemptStats = [];
  for (const config of configurations()) {
    const result = transformOverpassResponse(parsed, {
      bounds: BOUNDS,
      roadToleranceMeters: config.roadToleranceMeters,
      waterToleranceMeters: 300,
      minWaterAreaKm2: 2,
      coordinateDigits: config.coordinateDigits,
      allowedRoutes: config.allowedRoutes,
    });
    const cameras = snapCameras(result.roadSegments, CAMERA_TARGETS);
    const bounds = computeBounds(result.roadSegments, result.water, cameras);
    const data = { roadSegments: result.roadSegments, water: result.water, cameras, bounds };
    const moduleText = header + serializeGeometryData(data);
    const candidate = {
      config, result, cameras, bounds, moduleText,
      rawBytes: Buffer.byteLength(moduleText),
    };
    attemptStats.push({
      tolerance: config.roadToleranceMeters,
      digits: config.coordinateDigits,
      allowedRoutes: config.allowedRoutes.length,
      rawBytes: candidate.rawBytes,
      segments: result.stats.segments,
      roadPoints: result.stats.simplifiedPoints,
      waterRings: result.stats.waterRings,
      waterPoints: result.stats.waterPoints,
    });
    if (candidate.rawBytes <= MAX_RAW_BYTES) {
      assertCandidate(candidate);
      return candidate;
    }
  }
  throw new RangeError(
    `All ordered size levers failed: ${JSON.stringify(attemptStats)}`,
  );
}


function provenance(candidate, endpoint, responseHash) {
  const spanRows = REQUIRED_ROUTES.map((route) => {
    const span = candidate.result.corridorSpans[route];
    return `| ${route} | ${span.rawKm.toFixed(2)} | ${span.simplifiedKm.toFixed(2)} | ${span.retainedPercent.toFixed(1)}% |`;
  }).join("\n");
  const dropped = OPTIONAL_ROUTES.filter((route) =>
    !candidate.config.allowedRoutes.includes(route));
  return `# DFW Geometry Provenance

## Source

- Data: OpenStreetMap contributors
- License: Open Database License 1.0
- Attribution: © OpenStreetMap contributors
- Endpoint: ${endpoint}
- Snapshot date: ${SNAPSHOT_DATE}
- Raw response sha256: ${responseHash}

## Exact Overpass query

\`\`\`overpass
${QUERY}
\`\`\`

## Transformation

Motorway and trunk links are excluded by the query. Whitelisted roads are clipped segment by segment to the DFW bbox, canonicalized, deduplicated, simplified, and quantized. Concurrent route memberships remain on one physical segment. Water polygons larger than 2 square kilometers are clipped and simplified. Only outer rings are retained; holes are deliberately dropped because the fill is visually faint at hero scale.

## Extraction statistics

- Routes matched: ${candidate.result.stats.routes.join(", ")}
- Road segments: ${candidate.result.stats.segments}
- Road points before simplification: ${candidate.result.stats.rawPoints}
- Road points after simplification: ${candidate.result.stats.simplifiedPoints}
- Maximum measured road deviation: ${candidate.result.stats.maximumDeviationMeters.toFixed(2)} meters
- Water rings: ${candidate.result.stats.waterRings}
- Water points after simplification: ${candidate.result.stats.waterPoints}
- Road tolerance: ${candidate.config.roadToleranceMeters} meters
- Coordinate precision: ${candidate.config.coordinateDigits} decimals
- Optional routes dropped: ${dropped.length === 0 ? "none" : dropped.join(", ")}
- Generated module raw size: ${candidate.rawBytes} bytes

## Required corridor spans

| Route | Raw clipped span km | Simplified span km | Retained |
|---|---:|---:|---:|
${spanRows}

The derived geometry and this provenance file must be reviewed for ODbL share alike publication before a public launch. See \`docs/LAUNCH-CHECKLIST.md\`.
`;
}


async function main() {
  const { endpoint, raw, parsed } = await downloadSnapshot();
  const responseHash = createHash("sha256").update(raw).digest("hex");
  const candidate = selectCandidate(parsed, moduleHeader(endpoint, responseHash));
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  await mkdir(path.join(root, "data"), { recursive: true });
  await writeFile(path.join(root, "lib/dfw/geometry-data.ts"), candidate.moduleText, "utf8");
  await writeFile(
    path.join(root, "data/PROVENANCE.md"),
    provenance(candidate, endpoint, responseHash),
    "utf8",
  );
  console.log(JSON.stringify({
    endpoint,
    responseHash,
    rawBytes: candidate.rawBytes,
    config: candidate.config,
    stats: candidate.result.stats,
    corridorSpans: candidate.result.corridorSpans,
  }, null, 2));
}

main().catch((error) => {
  if (error instanceof AggregateError) {
    console.error(error.message);
    for (const cause of error.errors) {
      console.error(cause instanceof Error ? cause.stack : String(cause));
    }
  } else {
    console.error(error instanceof Error ? error.stack : String(error));
  }
  process.exitCode = 1;
});
